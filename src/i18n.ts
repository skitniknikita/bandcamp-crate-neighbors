export type CopyKey = keyof typeof translations.en;
export function translator(language: Language) {
  return (key: CopyKey, vars: Record<string, string | number> = {}) => {
    let value: string = translations[language][key];
    for (const [name, replacement] of Object.entries(vars)) value = value.replaceAll('{' + name + '}', String(replacement));
    return value;
  };
}
export function count(value: number, language: Language) { return new Intl.NumberFormat(language).format(value); }
